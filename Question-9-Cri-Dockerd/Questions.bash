# 题目：Cri-Dockerd

# 任务：
# 配置 cri-dockerd。
# 使用 dpkg 安装 Debian 包 ~/cri-dockerd.deb。
# 启用并启动 cri-docker 服务。
# 配置以下参数：
# 1. 将 net.bridge.bridge-nf-call-iptables 设置为 1
# 2. 将 net.ipv6.conf.all.forwarding 设置为 1
# 3. 将 net.ipv4.ip_forward 设置为 1
# 4. 将 net.netfilter.nf_conntrack_max 设置为 131072

